import shutil
import sys
import json
import glob
import os
import matplotlib
import matplotlib.pyplot

class Plotter:
    def __init__(self):
        self.data = []
        self.delta_subs = []
        self.best_name = "best"
        self.y_var = "fom_1"
        self.y_label = "Score"
        self.y_lambda = lambda y: y
        self.max_score = None # set to None to ignore this cut
        self.sub_cuts = {} # mapping from sub name to [lower_bound, upper_bound]; set to None to ignore a bound
        self.cut_list = []

    def load_one_dir_low_energy(self, a_dir):
        my_result = {}
        try:
            with open(f"{a_dir}/output.json") as fin:
                score_json = json.load(fin)
                my_result["score"] = score_json["score"]
        except FileNotFoundError:
            try:
                with open(f"{a_dir}/plot_output.json") as fin: # generated by plot_low_energy_cooling.py as a postprocessor job
                    score_json = json.load(fin)
                    my_result["score"] = score_json["score"]
            except Exception:
                return None
        if my_result["score"] > 1.0:
            return None
        with open(f"{a_dir}/config.json") as fin:
            my_result["config"] = json.load(fin)
        return my_result

    def load_one_dir_cooling(self, a_dir):
        my_result = {}
        score_json = None
        try:
            print(a_dir)
            with open(f"{a_dir}/optimisation") as fin:
                score_json = json.load(fin)
                cooling_score = score_json["optimisation"]["cooling a-pz"]["score"]
                et_us = my_result["score"] = cooling_score["us"]["emit_perp"]
                el_us = my_result["score"] = cooling_score["us"]["emit_long"]
                wt_us = my_result["score"] = cooling_score["us"]["weight"]

                et_ds = my_result["score"] = cooling_score["ds"]["emit_perp"]
                el_ds = my_result["score"] = cooling_score["ds"]["emit_long"]
                wt_ds = my_result["score"] = cooling_score["ds"]["weight"]
                if wt_us < 200:
                    return None

                my_result["score"] = cooling_score["total_score"]
                my_result["fom_product"] = et_ds/et_us*el_ds/el_us*(wt_us/wt_ds)**2
                my_result["fom_sum"] = et_ds/et_us+el_ds/el_us+(wt_us/wt_ds)**2
        except (FileNotFoundError, KeyError):
            if score_json:
                print(score_json["optimisation"].keys())
            sys.excepthook(*sys.exc_info())
            return None
        with open(f"{a_dir}/subs_list.json") as fin:
            my_result["config"] = {"substitutions":json.load(fin)[0]}
            my_result["config"]["run_dir"] = a_dir
        if self.is_cut(my_result):
            return None
        return my_result

    def is_cut(self, my_result):
        if self.max_score is not None and my_result[self.y_var] > self.max_score:
            return True
        subs = my_result["config"]["substitutions"]
        for sub_name in self.sub_cuts:
            [lower_bound, upper_bound] = self.sub_cuts[sub_name]
            if lower_bound is not None and subs[sub_name] < lower_bound:
                return True
            if upper_bound is not None and subs[sub_name] > upper_bound:
                return True
        return False


    def get_glob(self, dir_glob):
        dir_list = []
        if type(dir_glob) == type([]):
            for a_glob in dir_glob:
                dir_list += glob.glob(a_glob)
        else: # must be a string
            dir_list = glob.glob(dir_glob)
        return dir_list

    def load_files(self, dir_glob):
        self.data = []
        fail_counter, cut_counter = 0, 0
        dir_list = self.get_glob(dir_glob)
        for a_dir in dir_list[:]:
            if not os.path.isdir(a_dir):
                continue
            try:
                my_result = self.load_one_dir(a_dir)
                if my_result:
                    self.data.append(my_result)
                else:
                    cut_counter += 1
            except:
                fail_counter += 1
                if fail_counter < 3:
                    sys.excepthook(*sys.exc_info())
                elif fail_counter == 3:

                    print(">>>>>>>>>>>>>>>>>> Detected more than 3 fails, no bother printo <<<<<<<<<<<<<<<<<<<<")
        self.data = sorted(self.data, key=lambda item: item[self.y_var])
        self.get_deltas()
        print("Loaded", len(self.data), "with", fail_counter, "fails", cut_counter, "cuts and subs:")
        print(self.delta_subs)

    def get_deltas(self):
        delta_subs = set()
        ref_subs = self.data[0]["config"]["substitutions"]
        for item in self.data:
            subs = item["config"]["substitutions"]
            for key, value in subs.items():
                if ref_subs[key] != value:
                    delta_subs.add(key)
        self.delta_subs = sorted(list(delta_subs))

    def do_plots(self):
        if os.path.exists(self.plot_dir):
            shutil.rmtree(self.plot_dir)
        os.makedirs(self.plot_dir)
        for i, var_x in enumerate(self.delta_subs):
            self.plot_one_item(var_x)
            for var_y in self.delta_subs[i+1:]:
                self.plot_two_items(var_x, var_y)
        self.print_best()

    def plot_one_item(self, var_x):
        x_list = [item["config"]["substitutions"][var_x] for item in self.data]# if item["config"]["substitutions"]["__density_factor__"] < 1e-2]
        y_list = [self.y_lambda(item[self.y_var]) for item in self.data]# if item["config"]["substitutions"]["__density_factor__"] < 1e-2]
        x_label =  self.x_label(var_x)
        figure = matplotlib.pyplot.figure(x_label)
        axes = figure.add_subplot(1, 1, 1)
        axes.scatter(x_list, y_list, s=4)
        if var_x in self.log_scaling:
            axes.semilogx()
        axes.set_xlabel(x_label)
        axes.set_ylabel(self.y_label)
        axes.set_ylim(self.vmin, self.vmax)
        x_name = var_x.replace("__", "")
        figure.savefig(f"{self.plot_dir}/optimisation_{x_name}.png")

    def plot_two_items(self, var_x, var_y):
        x_list = [item["config"]["substitutions"][var_x] for item in self.data]# if item["config"]["substitutions"]["__density_factor__"] < 1e-2]
        y_list = [item["config"]["substitutions"][var_y] for item in self.data]# if item["config"]["substitutions"]["__density_factor__"] < 1e-2]
        z_list = [self.y_lambda(item[self.y_var]) for item in self.data]# if item["config"]["substitutions"]["__density_factor__"] < 1e-2]
        x_label =  self.x_label(var_x)
        y_label =  self.x_label(var_y)
        figure = matplotlib.pyplot.figure(x_label+" vs "+y_label)
        #axes = figure.add_subplot(1, 1, 1, projection="3d")
        #axes.stem(x_list, y_list, z_list, bottom=max(z_list))#, cmap="viridis", s=4)
        #axes.set_zlabel(self.y_label)
        axes = figure.add_subplot(1, 1, 1)
        scat = axes.scatter(x_list, y_list, c=z_list, cmap="viridis", s=4, vmin=self.vmin, vmax=self.vmax)
        if var_x in self.log_scaling and var_y in self.log_scaling:
            axes.loglog()
        elif var_x in self.log_scaling:
            axes.semilogx()
        elif var_y in self.log_scaling:
            axes.semilogy()

        axes.set_xlabel(x_label)
        axes.set_ylabel(y_label)
        x_name = var_x.replace("__", "")
        y_name = var_y.replace("__", "")
        figure.colorbar(scat)
        figure.savefig(f"{self.plot_dir}/optimisation_{x_name}_{y_name}.png")


    def get_path_root(self):
        path_list = [item['config']['run_dir'] for item in self.data]
        path_root = os.path.commonpath(path_list)
        path_root = os.path.realpath(path_root)
        return path_root

    def x_label(self, var_x):
        if var_x in self.labels:
            return self.labels[var_x]
        else:
            return var_x.replace("__", "").replace("_", " ")

    def print_best(self):
        print(f"Found best with score {self.data[0]['score']}")
        for key in self.delta_subs:
            print(f"{self.x_label(key):65s} {key:30s} {self.data[0]['config']['substitutions'][key]}")
        run_dir = self.data[0]['config']['run_dir']
        run_dir = os.path.realpath(run_dir)
        best_name = f"{self.get_path_root()}/{self.best_name}"
        print("In dir\n", "   ", run_dir)
        print(f"linked as {best_name}")
        if os.path.exists(best_name):
            os.unlink(best_name)
        print()
        os.symlink(run_dir, best_name)


    labels = {
        "__dt1__":"Reacceleration pulse start time [ns]",
        "__ez2__":"Reacceleration pulse magnitude [MV/m]",
        "__ez1__":"Deceleration pulse magnitude [MV/m]",
        "__flat1__":"Reacceleration pulse length [ns]",
        "__rf1_pulse_beta_rel__":"Reacceleration pulse velocity [mm/ns]",
        "__zoff2__":"Deceleration pulse z standoff [mm]",
        "__density_factor__":"Density of He [Fraction of stp]",
        "__pf1__":"Reacceleration pulse fraction of Paschen breakdown voltage",
        "__pf2__":"Deceleration pulse fraction of Paschen breakdown voltage",
        "__pd__":"Paschen distance used in Paschen voltage calculation [mm]",
        "__n_events__":"Number of initial events",
        "__full_length__":"Cooling cell length [mm]",
    }
    log_scaling = [
        "__density_factor__",
        "__ez2__",
    ]

def low_energy_muons(plotter):
    plotter.plot_dir = "output/v055/"
    plotter.y_label = "Transmission [%]"
    plotter.y_lambda = lambda y: (1-y)*100
    plotter.load_one_dir = plotter.load_one_dir_low_energy
    plotter.load_files(["output/v055/*"])

def cooling(plotter):
    run_dir = "output/v069/"
    plotter.y_var = "fom_sum" # fom_sum or fom_product
    if plotter.y_var == "fom_sum":
        plotter.y_label = "$\\frac{\\varepsilon_\\perp^{ds}}{\\varepsilon_\\perp^{us}} + "+\
                           "\\frac{\\varepsilon_{l}^{ds}}{\\varepsilon_{l}^{us}} + \\frac{1}{T_{trans}^2}$"
        plotter.vmin, plotter.vmax = [2.5, 3.25]
        plotter.max_score = 5.0
    elif plotter.y_var == "fom_product":
        plotter.y_label = "$\\frac{\\varepsilon_\\perp^{ds}}{\\varepsilon_\\perp^{us}}\\,\\frac{\\varepsilon_{l}^{ds}}{\\varepsilon_{l}^{us}}\\,\\frac{1}{T_{trans}^2}$"
        plotter.vmin, plotter.vmax = [0.5, 1.5]
        plotter.max_score = 1.5
    else:
        raise RuntimeError("Did not recognise y_var")
    plotter.best_name = f"{plotter.y_var}_{plotter.best_name}"
    plotter.plot_dir = f"{run_dir}/{plotter.y_var}_optimisation_plot/"
    plotter.sub_cuts = {}
    plotter.y_lambda = lambda y: y
    plotter.load_one_dir = plotter.load_one_dir_cooling
    plotter.load_files(f"{run_dir}/name*")

def cleanup(plotter, files_to_clean):
    root_dir = plotter.get_path_root()
    print("Cleaning", root_dir)
    dirlist = sorted(glob.glob(f"{root_dir}/*"))
    tmp_dirlist = [d for d in dirlist]
    for a_dir in tmp_dirlist:
        if os.path.islink(a_dir):
            realpath = os.path.realpath(a_dir)
            try:
                dirlist.remove(a_dir) # if we have multiple symlinks pointing at same directory, remove(realpath) will throw ValueError
                dirlist.remove(realpath)
            except ValueError:
                print("Failed to remove realpath ", realpath, "from", a_dir)
            print(f"    Not cleaning {realpath} pointed by {a_dir}")
    print(f"   Cleaning {len(dirlist)}/{len(tmp_dirlist)}")
    for i, a_dir in enumerate(dirlist):
        for a_file in files_to_clean:
            targets = glob.glob(f"{a_dir}/{a_file}")
            if i < 10 and len(targets) > 0:
                print(f"      e.g. {a_dir}")
            for a_target in targets:
                if i == 0:
                    print(f"       {a_target.replace(a_dir, '')}")
                os.unlink(a_target)

def main():
    plotter = Plotter()
    #low_energy_muons(plotter)
    cooling(plotter)
    plotter.do_plots()
    if "--cleanup" in sys.argv:
        cleandir = "tmp/optimisation/*/"
        cleanup(plotter, [cleandir+"output.txt", cleandir+"beam.tmp", cleandir+"solenoid_field_map.txt"])

if __name__ == "__main__":
    main()
    matplotlib.pyplot.show(block=False)
    input("Press <CR> to finish")

